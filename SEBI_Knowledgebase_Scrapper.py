def process_sebi_rss_feed():
    """Monitors the SEBI RSS feed and queues items for download."""
    # ... (Logic remains the same as in the previous script)
    print("\n--- Processing SEBI Real-Time RSS Feed ---")
    rss_links = []
    try:
        feed = feedparser.parse(SEBI_NOTIFICATIONS_FEED)
        for entry in feed.entries:
            title = entry.get('title', 'No Title')
            link = entry.get('link', None)
            category = entry.get('sebi_category', entry.get('tags', [{}])[0].get('term', 'Document'))
            source_key = category.replace(' ', '_').strip()
            
            if link:
                rss_links.append({
                    'title': title, 
                    'link': link, 
                    'source_key': f"RSS_{source_key}" # Prefix with RSS for clarity
                })
    except Exception as e:
        print(f"--- [CRITICAL ERROR] Could not parse SEBI RSS feed: {e}")
    return rss_links

def scrape_sebi_index_page(source_key, index_url):
    """
    Scrapes a SEBI index page which uses a consistent table format.
    The SEBI tables typically have columns: Date, Type, Title/Link.
    """
    print(f"\n--- Scraping Index: {source_key} ({index_url}) ---")
    document_links = []
    
    try:
        response = requests.get(index_url, timeout=20)
        response.raise_for_status()
        soup = BeautifulSoup(response.content, 'html.parser')
        
        # SEBI often uses simple tables within the main content area
        main_table = soup.find('table') 
        if not main_table:
            print(f"[WARNING] Could not find the main data table on {source_key}.")
            return []

        # 1. Get headers (used for alignment verification)
        headers = [th.text.strip().replace('\n', ' ') for th in main_table.find('tr').find_all(['th', 'td'])]
        # Common SEBI columns: ['Date', 'Type', 'Title'] or ['Issued Year', 'Regulations']
        
        # 2. Iterate over data rows (skip header row)
        rows = main_table.find_all('tr')[1:] 
        
        for row in rows:
            cols = row.find_all('td')
            if len(cols) < 2: 
                continue # Skip empty or malformed rows

            # Attempt to extract Date (often Col 0), Type (Col 1), and Title/Link (Col 2 or 1)
            date_text = cols[0].text.strip() if len(cols) > 0 else "N/A"
            type_text = cols[1].text.strip() if len(cols) > 1 else source_key
            title = None
            link = None
            
            # Find the link element (a tag) within the available columns
            link_element = row.find('a', href=True)
            if link_element:
                link = urljoin(index_url, link_element['href'])
                title = link_element.text.strip()
            
            if title and link:
                document_links.append({
                    'title': title, 
                    'link': link, 
                    'source_key': f"{source_key}_{type_text.replace(' ', '_')}", # e.g., Circulars_Regulations
                    'metadata_date': date_text
                })
                    
        print(f"Found {len(document_links)} potential document links on {source_key} index.")
        
    except requests.exceptions.RequestException as e:
        print(f"   [CRITICAL ERROR] Failed to fetch index page {index_url}: {e}")
        
    return document_links


def process_all_links(all_document_links):
    """
    Iterates through all collected SEBI document links, checks the audit file, 
    and downloads only new or failed records.
    """
    global download_status_tracker
    unique_links = set()
    print(f"\n--- Starting Processing of {len(all_document_links)} Total Links ---")
    
    skipped_count = 0
    download_queue = []
    
    # Filter the list based on audit status
    for doc in all_document_links:
        link = doc['link']
        
        # Check 1: Audit status
        if link in download_status_tracker and download_status_tracker[link]['downloaded']:
            skipped_count += 1
            continue
            
        # Check 2: Deduplication within the current run
        if link in unique_links:
            continue
            
        unique_links.add(link)
        download_queue.append(doc)

    print(f"Skipped {skipped_count} documents already marked as successful.")
    print(f"Processing {len(download_queue)} new or failed documents.")

    # Process the download queue (download logic is the same)
    for doc in download_queue:
        link = doc['link']
        title = doc['title']
        source_key = doc['source_key']
        
        print(f"\n[PROCESSING] {source_key} - {title[:80]}...")
        
        pdf_url = None
        
        if link.lower().endswith('.pdf'):
            pdf_url = link
        else:
            pdf_url = find_pdf_link(link)
        
        success = False
        filename = None
        
        if pdf_url:
            filename = sanitize_filename(title, source_key)
            
            # Check if file exists on disk
            if os.path.exists(os.path.join(DOWNLOAD_DIR, filename)):
                print(f"   [SKIP] File already exists on disk: {filename}")
                success = True
            else:
                success = download_file(pdf_url, filename)
        else:
            print("   [FAILED] Could not find a downloadable PDF link.")
        
        # Update Status Tracker
        download_status_tracker[link] = {
            'title': title, 
            'source': source_key,
            'downloaded': success, 
            'filename': filename if success else None,
            'final_pdf_url': pdf_url,
            'source_html_link': link,
            'metadata_date': doc.get('metadata_date', 'N/A') # Add the date from the index
        }

def main():
    """Orchestrates the SEBI scraping process (RSS + Index)."""
    global download_status_tracker
    download_status_tracker = load_status(STATUS_FILE)
    setup_directory()
    
    all_document_links = []
    
    # STEP 1: Process the SEBI RSS Feed (Real-time updates)
    all_document_links.extend(process_sebi_rss_feed())
    
    # STEP 2: Scrape the SEBI Index pages (Historical/Comprehensive coverage)
    for source_key, url in SEBI_INDEX_URLS.items():
        links = scrape_sebi_index_page(source_key, url)
        all_document_links.extend(links)
        
    # STEP 3: Process and download all unique document links
    process_all_links(all_document_links)

    # STEP 4: Save the final audit status
    save_status(download_status_tracker, STATUS_FILE)
    
    # 5. Final summary
    downloaded_count = sum(1 for status in download_status_tracker.values() if status['downloaded'])
    failed_count = sum(1 for status in download_status_tracker.values() if not status['downloaded'])
    print(f"\n===========================================")
    print(f"| SEBI Ingestion Summary:")
    print(f"| Total Unique Documents Tracked: {len(download_status_tracker)}")
    print(f"| Successfully Downloaded: {downloaded_count}")
    print(f"| Failed Downloads: {failed_count}")
    print(f"| Audit Saved to: {STATUS_FILE}")
    print(f"===========================================")
    
if __name__ == '__main__':
    main()