import feedparser
import requests
import os
import datetime
import json
from urllib.parse import urljoin
from bs4 import BeautifulSoup

# --- Configuration ---
SEBI_NOTIFICATIONS_FEED = 'https://www.sebi.gov.in/rss/rss.xml'

# Dictionary of URLs for INDEX PAGES to scrape (Circulars, Regulations, etc.)
# These pages use tables listing documents. The 'search=...' parameter often gives the list.
SEBI_INDEX_URLS = {
    # CRITICAL: Official Instructions & Guidelines
    'Circulars': 'https://www.sebi.gov.in/sebiweb/home/HomeAction.do?doListingAll=yes&search=Circular',
    # CRITICAL: Consolidated Rules (like RBI's Master Directions)
    'Master_Circulars': 'https://www.sebi.gov.in/sebiweb/home/HomeAction.do?doListingAll=yes&search=Master%20Circulars',
    # Foundational legal documents
    'Regulations': 'https://www.sebi.gov.in/sebiweb/home/HomeAction.do?doListingLegal=yes&sid=1&ssid=3&smid=0',
    # Major announcements
    'Press_Releases': 'https://www.sebi.gov.in/sebiweb/home/HomeAction.do?doListingAll=yes&search=Press%20Release',
}

DOWNLOAD_DIR = 'sebi_knowledge_base'
STATUS_FILE = 'sebi_download_audit_status.json'

# Global tracker for status and duplicate checks
download_status_tracker = {}

# --- Utility Functions (Same as previous script) ---

def load_status(file_path):
    # ... (omitted for brevity)
    if os.path.exists(file_path):
        try:
            with open(file_path, 'r') as f:
                return json.load(f)
        except json.JSONDecodeError:
            print(f"[WARNING] Could not decode {file_path}. Starting fresh tracker.")
            return {}
    return {}

def save_status(data, file_path):
    # ... (omitted for brevity)
    with open(file_path, 'w') as f:
        json.dump(data, f, indent=4)
    print(f"\n--- Data saved to {file_path} ---")

def setup_directory():
    # ... (omitted for brevity)
    if not os.path.exists(DOWNLOAD_DIR):
        os.makedirs(DOWNLOAD_DIR)
        print(f"Created download directory: {DOWNLOAD_DIR}")

def sanitize_filename(title, source_key):
    # ... (omitted for brevity)
    date_str = datetime.datetime.now().strftime('%Y%m%d')
    safe_title = ''.join(c if c.isalnum() or c in (' ', '_', '-') else '' for c in title)
    safe_title = safe_title.strip().replace(' ', '_')
    filename = f"{source_key}_{date_str}_{safe_title}.pdf"
    return filename[:200]

def download_file(pdf_url, filename):
    # ... (omitted for brevity)
    try:
        full_path = os.path.join(DOWNLOAD_DIR, filename)
        if os.path.exists(full_path):
            print(f"   [SKIP] File already exists: {filename}")
            return True
        response = requests.get(pdf_url, stream=True, timeout=30)
        response.raise_for_status()
        with open(full_path, 'wb') as f:
            for chunk in response.iter_content(chunk_size=8192): 
                f.write(chunk)
        print(f"   [SUCCESS] Downloaded: {filename}")
        return True
    except requests.exceptions.RequestException as e:
        print(f"   [ERROR] Failed to download {pdf_url}: {e}")
        return False
