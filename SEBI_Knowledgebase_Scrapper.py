def find_pdf_link(html_url):
    """
    Visits the SEBI document page and reliably searches for the direct PDF download link,
    prioritizing links related to the consistent download structure (like the <button id=download>
    or adjacent PDF links).
    """
    try:
        response = requests.get(html_url, timeout=15)
        response.raise_for_status()
        soup = BeautifulSoup(response.content, 'html.parser')
        
        # 1. Look for the <button id="download"> element
        download_button = soup.find('button', id='download')
        
        if download_button:
            # The PDF link might be stored in a data attribute (e.g., data-pdf-url) 
            # or generated by JavaScript. The safest scrape is to look for the final PDF link 
            # *near* the button.

            # Look for the last anchor tag (<a>) on the page that links to a PDF, 
            # as this is often the final resolved URL in the viewer.
            
            # Find all potential PDF links
            pdf_links = [a for a in soup.find_all('a', href=True) if a['href'].lower().endswith('.pdf')]
            
            if pdf_links:
                # Often the last PDF link found is the largest/correct one to download
                final_pdf_link = pdf_links[-1]['href']
                print(f"   -> Found PDF link via download button proximity/consistency.")
                return urljoin(html_url, final_pdf_link)

        # 2. Fallback to generic PDF link search if the button/proximity check fails
        for link_element in soup.find_all('a', href=True):
            href = link_element['href']
            
            # Pattern 1: Links ending with .pdf (Direct link)
            if href.lower().endswith('.pdf'):
                return urljoin(html_url, href)
                
            # Pattern 2: Links containing specific document identifiers in the path
            if ('/legal/circulars/' in href.lower() or '/pr/' in href.lower()) and any(ext in href.lower() for ext in ['.pdf', '.doc', '.docx']):
                return urljoin(html_url, href)

    except requests.exceptions.RequestException as e:
        print(f"   [ERROR] Failed to fetch HTML page {html_url}: {e}")
        
    return None

